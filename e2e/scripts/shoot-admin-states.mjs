// Captures admin interaction states (login, denied, dialogs, drawer) for docs/screens/admin.
import { chromium } from '@playwright/test';

const ADMIN = process.env.ADMIN_URL ?? 'http://localhost:5174';
const API = process.env.API_URL ?? 'http://localhost:4013';
const out = '../docs/screens/admin';
await fetch(`${API}/dev/reset`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ scenario: 'default' }) });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
const shot = async (name) => (await page.waitForTimeout(700), await page.screenshot({ path: `${out}/${name}-1440.png` }), console.log('saved', name));
const login = async (email, password) => {
  await page.goto(`${ADMIN}/connexion`);
  await page.getByTestId('email').fill(email);
  await page.getByTestId('password').fill(password);
  await page.getByTestId('login-submit').click();
  await page.getByRole('heading', { name: 'Centre des opérations' }).waitFor();
};
await page.goto(`${ADMIN}/connexion`);
await shot('A00-session');
await login('youssra@naya.demo', 'Naya-Support-2026');
await page.goto(`${ADMIN}/finance`);
await shot('A00-denied');
await page.getByTestId('logout').click();
await login('meryem@naya.demo', 'Naya-Admin-2026');
await page.goto(`${ADMIN}/verifications/VP-002`);
await page.getByTestId('request-more').click();
await page.getByTestId('correct-id_back').check();
await page.getByTestId('note-id_back').fill('Le verso est coupé : reprenez la photo en entier.');
await page.getByTestId('decision-message').fill('Merci de reprendre le verso de votre pièce.');
await shot('A05-more');
await page.keyboard.press('Escape');
await page.getByTestId('reject').click();
await shot('A05-reject');
await page.keyboard.press('Escape');
await page.getByTestId('approve').click();
await shot('A05-confirm');
await page.getByTestId('confirm-decision').click();
await page.getByText(/Décision : approuvé/).waitFor();
await shot('A05-done');
await page.goto(`${ADMIN}/finance`);
await page.getByTestId('correct-DR-001').click();
await page.getByTestId('correction-amount').fill('5');
await page.getByTestId('correction-reason').fill('Remboursement d’un péage justifié par ticket.');
await page.getByTestId('correction-next').click();
await shot('A09-correction-confirm');
await page.getByTestId('correction-confirm').click();
