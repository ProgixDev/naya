export type IconComponent = IconsaxIcon;

function createIcon(Glyph: IconsaxIcon, rotate?: string): IconComponent {
  return function NayaIcon({ size = 24, color = '#292D32', variant = 'Linear', style, ...props }: IconsaxProps) {
    const iconStyle = rotate ? [style, { transform: [{ rotate }] }] : style;
    return <Glyph {...props} size={size} color={color} variant={variant} style={iconStyle} />;
  };
}

